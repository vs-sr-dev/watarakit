"""Recompile a Supervision cartridge to C++ and build it.

    python -m watarakit.recomp ROM.sv --trace TRACEDIR --out build/recomp/GAME [--build]
    build/recomp/GAME/sv.exe ROM.sv --lockstep --frames 6000

The output directory gets `funcs.h` (every native function), `game_N.cpp`
(the functions, a few hundred per file), `register.cpp`
(`sv_register_all`), and with --build, `sv.exe`: the runtime
(watarakit/runtime) linked with the game's code, built with g++ (msys2's
ucrt64; SDL2 for --window when it is there).
"""
import argparse
import concurrent.futures
import os
import shutil
import subprocess
import sys

from .. import cart as cartmod
from . import discover, emit

HERE = os.path.dirname(os.path.abspath(__file__))
RUNTIME = os.path.join(os.path.dirname(HERE), 'runtime')
RUNTIME_SRC = ['sv_core.cpp', 'sv_audio.cpp', 'sv_main.cpp']
GXX_DIR = r'C:\msys64\ucrt64\bin'


def generate(rom, trace, out, per_file=300, comments=True, log=print):
    c = cartmod.Cart.load(rom)
    tr = discover.Trace(trace, c) if trace else None
    prog = discover.Program(c, tr).discover()
    os.makedirs(out, exist_ok=True)
    funcs = [prog.funcs[k] for k in sorted(prog.funcs)]
    with open(os.path.join(out, 'funcs.h'), 'w') as f:
        f.write('// generated by watarakit.recomp from %s\n#pragma once\n#include "sv.h"\n'
                % os.path.basename(rom))
        for fn in funcs:
            f.write(f'void {fn.name}(Sv& c);\n')
    sites = {}
    files = []
    for n in range(0, len(funcs), per_file):
        path = os.path.join(out, f'game_{n // per_file}.cpp')
        files.append(path)
        with open(path, 'w') as f:
            f.write('// generated by watarakit.recomp\n#include "funcs.h"\n\n')
            for fn in funcs[n:n + per_file]:
                b = emit.Body(prog, fn, comments)
                f.write('\n'.join(b.emit()) + '\n\n')
                for k, v in b.sites.items():
                    sites[k] = sites.get(k, 0) + v
    with open(os.path.join(out, 'register.cpp'), 'w') as f:
        f.write('// generated by watarakit.recomp\n#include "funcs.h"\n\nvoid sv_register_all() {\n')
        for fn in funcs:
            f.write(f'    sv_register({fn.slot}, 0x{fn.entry:04X}, {fn.name});\n')
        f.write('}\n')
    files.append(os.path.join(out, 'register.cpp'))
    insns = sum(len(fn.code) for fn in funcs)
    log(f'{c.name}: {len(funcs)} functions, {insns} instructions -> {len(files)} files; '
        + ', '.join(f'{k} {v}' for k, v in sorted(sites.items())))
    cov = prog.coverage()
    if cov:
        log(f'  traced instructions held by a function: {cov[0]}/{cov[1]}')
    return files


def build(out, files, opt='-O1', log=print):
    env = dict(os.environ)
    if os.path.isdir(GXX_DIR):
        env['PATH'] = GXX_DIR + os.pathsep + env.get('PATH', '')
    gxx = shutil.which('g++', path=env['PATH']) or 'g++'
    sdl = os.path.isfile(os.path.join(os.path.dirname(GXX_DIR), 'include', 'SDL2', 'SDL.h'))
    flags = ['-std=c++17', opt, '-w', f'-I{RUNTIME}', f'-I{out}']
    if sdl:
        flags.append('-DSV_SDL')
    objs_dir = os.path.join(out, 'obj')
    os.makedirs(objs_dir, exist_ok=True)
    srcs = [os.path.join(RUNTIME, s) for s in RUNTIME_SRC] + files

    def cc(src):
        obj = os.path.join(objs_dir, os.path.splitext(os.path.basename(src))[0] + '.o')
        if os.path.exists(obj) and os.path.getmtime(obj) > os.path.getmtime(src) \
                and src not in files and os.path.getmtime(obj) > os.path.getmtime(
                    os.path.join(RUNTIME, 'sv.h')):
            return obj
        r = subprocess.run([gxx, *flags, '-c', src, '-o', obj], env=env,
                           capture_output=True, text=True)
        if r.returncode:
            raise RuntimeError(f'{src}:\n{r.stderr[:4000]}')
        return obj
    with concurrent.futures.ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as ex:
        objs = list(ex.map(cc, srcs))
    exe = os.path.join(out, 'sv.exe')
    libs = ['-lmingw32', '-lSDL2main', '-lSDL2'] if sdl else []
    r = subprocess.run([gxx, *objs, '-o', exe, '-static-libgcc', '-static-libstdc++', *libs],
                       env=env, capture_output=True, text=True)
    if r.returncode:
        raise RuntimeError(r.stderr[:4000])
    dll = os.path.join(GXX_DIR, 'SDL2.dll')
    if sdl and os.path.isfile(dll):
        shutil.copy2(dll, out)
    log(f'  built {exe}')
    return exe


def main(argv=None):
    ap = argparse.ArgumentParser(prog='watarakit.recomp')
    ap.add_argument('rom')
    ap.add_argument('--trace')
    ap.add_argument('--out', required=True)
    ap.add_argument('--build', action='store_true')
    ap.add_argument('--no-comments', action='store_true')
    ap.add_argument('-O', dest='opt', default='1')
    a = ap.parse_args(argv)
    files = generate(a.rom, a.trace, a.out, comments=not a.no_comments)
    if a.build:
        build(a.out, files, opt='-O' + a.opt)


if __name__ == '__main__':
    sys.exit(main())
